export function countryMapPoint(code: string): { x: number; y: number } | null {
  const c = COUNTRY_CENTROIDS[code];
  if (!c) return null;
  return {
    x: ((c.lng + 180) / 360) * 1000,
    y: ((90 - c.lat) / 180) * 500,
  };
}

export function countryLabel(code: string): string {
  if (!code || code === "ZZ" || code === "XX") return "Unknown";
  if (code === "T1") return "Tor / Anonymous";
  try {
    return new Intl.DisplayNames(["en"], { type: "region" }).of(code) || code;
  } catch {
    return code;
  }
}

export function flagEmoji(code: string): string {
  if (!code || code === "ZZ" || code === "XX" || code === "T1" || code.length !== 2) return "🌐";
  const upper = code.toUpperCase();
  if (!/^[A-Z]{2}$/.test(upper)) return "🌐";
  const chars = [...upper].map((c) => 0x1f1e6 + (c.charCodeAt(0) - 65));
  return String.fromCodePoint(...chars);
}
